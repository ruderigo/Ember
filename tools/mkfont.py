# Generates src/font.h: anti-aliased ASCII glyph atlases (alpha bytes) from DejaVu Sans Mono.
import sys
from PIL import Image, ImageDraw, ImageFont
PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
out = []
out.append("/* Generated by tools/mkfont.py from DejaVu Sans Mono (Bitstream Vera license, free to embed). */")
out.append("#pragma once")
out.append("typedef struct { int w, h; const unsigned char *data; } EmberFont; /* 95 glyphs, ASCII 32..126, each w*h alpha bytes */")
for name, path, size in [("font_small", PATH, 18), ("font_med", BOLD, 24), ("font_big", BOLD, 56)]:
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    w = int(round(f.getlength("M"))); h = asc + desc
    data = []
    for c in range(32, 127):
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((0, 0), chr(c), font=f, fill=255)
        data.extend(im.tobytes())
    out.append(f"static const unsigned char {name}_data[{len(data)}] = {{")
    for i in range(0, len(data), 40):
        out.append(",".join(str(b) for b in data[i:i+40]) + ",")
    out.append("};")
    out.append(f"static const EmberFont {name} = {{ {w}, {h}, {name}_data }};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
